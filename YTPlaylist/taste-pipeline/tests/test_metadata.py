def test_fetch_metadata_enforces_bound_and_logs_deferral(
    monkeypatch: pytest.MonkeyPatch,
    config: Config,
    state: StateStore,
    caplog: pytest.LogCaptureFixture,
) -> None:
    # Given 200 candidate ids and a bound of 3
    _patch_extractor(monkeypatch, _default_fixtures())
    config = dataclasses.replace(config, max_metadata_fetch=3)
    video_ids = [SONG_ID, TALK_ID, SONG_ID] + [f"defer{i:07d}" for i in range(197)]

    # When fetching metadata with logging captured
    with caplog.at_level(logging.INFO, logger="taste_pipeline.metadata"):
        results = fetch_metadata(video_ids, config, state)

    # Then exactly 3 videos were fetched (one per extract call) and 197 deferred
    assert len(results) == 3
    assert any("deferring 197 ids" in record.message for record in caplog.records)


def test_fetch_metadata_skips_deleted_video_and_continues(
    monkeypatch: pytest.MonkeyPatch,
    config: Config,
    state: StateStore,
    caplog: pytest.LogCaptureFixture,
) -> None:
    # Given three ids of which the middle one is deleted
    fixtures = _default_fixtures()
    _patch_flaky_extractor(monkeypatch, fixtures, failing_ids={"dead0000001"})

    # When fetching metadata with logging captured
    with caplog.at_level(logging.WARNING, logger="taste_pipeline.metadata"):
        results = fetch_metadata([SONG_ID, "dead0000001", TALK_ID], config, state)

    # Then the two live videos are returned, no exception escapes, and the skip is logged
    assert [meta.video_id for meta in results] == [SONG_ID, TALK_ID]
    assert any("dead0000001" in record.message for record in caplog.records)


def test_fetch_metadata_records_fetched_ids_as_metadata_stage(
    monkeypatch: pytest.MonkeyPatch, config: Config, state: StateStore
) -> None:
    # Given both fixtures available
    _patch_extractor(monkeypatch, _default_fixtures())

    # When fetching metadata
    _ = fetch_metadata([SONG_ID, TALK_ID], config, state)

    # Then every fetched id is in the seen-history (recorded with stage 'metadata')
    assert state.already_seen(SONG_ID)
    assert state.already_seen(TALK_ID)
    stages = _read_stages(state.db_path)
    assert stages == {SONG_ID: "metadata", TALK_ID: "metadata"}


def test_fetch_metadata_configures_yt_dlp_for_full_readonly_extraction(
    monkeypatch: pytest.MonkeyPatch, config: Config, state: StateStore
) -> None:
    # Given the fake extractor capturing the params YoutubeDL was built with
    captured = _patch_extractor(monkeypatch, _default_fixtures())

    # When fetching metadata for one id
    _ = fetch_metadata([SONG_ID], config, state)

    # Then yt-dlp is configured for a full, read-only, cookie-authenticated extraction
    assert len(captured) == 1
    params = captured[0]
    assert params["skip_download"] is True
    assert params["cookiefile"] == str(config.cookie_file)
    assert params["quiet"] is True
    assert params["no_warnings"] is True
    # Guardrails: pass B must not reuse pass A's flat-listing or download-archive flags
    assert "extract_flat" not in params
    assert "download_archive" not in params


def test_metadata_json_round_trip(
    monkeypatch: pytest.MonkeyPatch, config: Config, state: StateStore
) -> None:
    # Given metadata fetched from the recorded fixtures
    _patch_extractor(monkeypatch, _default_fixtures())
    results = fetch_metadata([SONG_ID, TALK_ID], config, state)

    # When serializing to JSON and back (through a real json.dumps/loads cycle)
    for meta in results:
        raw = json.loads(json.dumps(metadata_to_json(meta)))
        rebuilt = metadata_from_json(cast("Mapping[str, object]", raw))

        # Then the rebuilt value equals the original
        assert rebuilt == meta
        assert isinstance(rebuilt, TrackMetadata)
