FIXTURE_DIR = Path(__file__).parent / "fixtures"
SONG_FIXTURE = FIXTURE_DIR / "full_meta_song.json"
TALK_FIXTURE = FIXTURE_DIR / "full_meta_talk.json"
SONG_ID = "song0000001"
TALK_ID = "talk0000001"


def _load_fixture(path: Path) -> dict[str, object]:
    """Load a recorded full info dict; json.loads is the untyped boundary."""
    return cast("dict[str, object]", json.loads(path.read_text(encoding="utf-8")))


def _patch_extractor(
    monkeypatch: pytest.MonkeyPatch, by_id: Mapping[str, dict[str, object]]
) -> list[dict[str, object]]:
    """Replay fixture info dicts through a fake extractor; return captured YoutubeDL params."""
    captured: list[dict[str, object]] = []

    def fake_extract_info(self: YoutubeDL, url: str, *, download: bool = False) -> dict[str, object]:
        _ = download
        captured.append(dict(self.params))
        video_id = url.rsplit("=", maxsplit=1)[-1]
        return by_id[video_id]

    monkeypatch.setattr(YoutubeDL, "extract_info", fake_extract_info)
    return captured


def _patch_flaky_extractor(
    monkeypatch: pytest.MonkeyPatch, by_id: Mapping[str, dict[str, object]], failing_ids: set[str]
) -> None:
    """Fake extractor raising ``DownloadError`` for ``failing_ids`` like a deleted/private video."""
    unavailable = "Video unavailable"

    def fake_extract_info(self: YoutubeDL, url: str, *, download: bool = False) -> dict[str, object]:
        _ = (self, download)
        video_id = url.rsplit("=", maxsplit=1)[-1]
        if video_id in failing_ids:
            raise DownloadError(unavailable)
        return by_id[video_id]

    monkeypatch.setattr(YoutubeDL, "extract_info", fake_extract_info)


def _default_fixtures() -> dict[str, dict[str, object]]:
    song = _load_fixture(SONG_FIXTURE)
    talk = _load_fixture(TALK_FIXTURE)
    return {SONG_ID: song, TALK_ID: talk}


def _read_stages(db_path: Path) -> dict[str, str]:
    with sqlite3.connect(db_path) as conn:
        rows = conn.execute("SELECT video_id, stage FROM seen").fetchall()
    return {row[0]: row[1] for row in rows}


@pytest.fixture
def config(tmp_path: Path) -> Config:
    data_dir = tmp_path / "data"
    return Config(
        like_library_dir=tmp_path,
        data_dir=data_dir,
        cookie_file=tmp_path / "cookies.txt",
        download_archive=data_dir / "yt-dlp-archive.txt",
        max_metadata_fetch=150,
    )


@pytest.fixture
def state(config: Config) -> Iterator[StateStore]:
    store = StateStore(config.data_dir)
    yield store
    store.close()


def test_fetch_metadata_normalizes_art_track_fields(
    monkeypatch: pytest.MonkeyPatch, config: Config, state: StateStore
) -> None:
    # Given a recorded Art Track info dict replayed through the fake extractor
    _patch_extractor(monkeypatch, _default_fixtures())

    # When fetching metadata for the song id
    results = fetch_metadata([SONG_ID], config, state)

    # Then the Art Track fields are normalized: Music category, track/artist/album
    # present, timestamp as int, duration as float, and the auto-generated footer
    assert len(results) == 1
    meta = results[0]
    assert meta.video_id == SONG_ID
    assert meta.title == "siqlo - Hack and Slash"
    assert meta.uploader == "siqlo - Topic"
    assert meta.uploader_id == "@siqlo-topic"
    assert meta.channel_id == "UC2222222222222222222222"
    assert meta.upload_date == "20240115"
    assert meta.timestamp == 1705276800
    assert meta.categories == ["Music"]
    assert meta.duration == 187.0
    assert isinstance(meta.duration, float)
    assert meta.description is not None
    assert meta.description.endswith("Auto-generated by YouTube.")
    assert meta.track == "Hack and Slash"
    assert meta.artist == "siqlo"
    assert meta.album == "Hack and Slash"
    assert meta.thumbnail_url == "https://i.ytimg.com/vi/song0000001/maxresdefault.jpg"
    assert meta.webpage_url == f"https://www.youtube.com/watch?v={SONG_ID}"


